function t(key, lang) {
  const dict = translations[lang] || translations.fr;
  return dict[key] !== undefined ? dict[key] : (translations.fr[key] || key);
}

function applyLanguage(lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL_LANGS.includes(lang) ? 'rtl' : 'ltr';

  document.querySelectorAll('[data-i18n-href]').forEach((el) => {
    el.href = t(el.getAttribute('data-i18n-href'), lang);
  });

  document.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
    el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label'), lang));
  });

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const value = t(key, lang);
    if (value.includes('<br>')) {
      el.innerHTML = value;
    } else {
      el.textContent = value;
    }
  });

  try {
    localStorage.setItem('dat_lang', lang);
  } catch (e) { /* storage unavailable, ignore */ }
}

function getSavedLanguage() {
  let lang = null;
  try {
    lang = localStorage.getItem('dat_lang');
  } catch (e) { /* storage unavailable, ignore */ }
  return translations[lang] ? lang : 'fr';
}
